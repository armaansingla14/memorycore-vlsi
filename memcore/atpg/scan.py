"""Scan-chain insertion and scan-test pattern export.

``insert_scan`` turns a gate-level sequential .bench circuit into structural
Verilog in which every ``dff`` is replaced by a mux-D scan flop (``sdff``)
and the flops are stitched into a single chain::

    scan_in -> F0 -> F1 -> ... -> F(N-1) -> scan_out

``export_patterns`` converts full-scan ATPG patterns into a vector file that
the Verilog testbench applies through the chain (load, capture, unload).
"""
from __future__ import annotations

from .bench import Circuit, _vname
from .faultsim import FaultSimulator

CELLS_V = """// Scan cell library (behavioural)
`timescale 1ns/1ps
module dff (input wire clk, input wire d, output reg q);
    always @(posedge clk) q <= d;
endmodule

module sdff (input wire clk, input wire d, input wire si, input wire se, output reg q);
    always @(posedge clk) q <= se ? si : d;
endmodule
"""


def insert_scan(c: Circuit, module: str | None = None, chain: list[str] | None = None) -> str:
    """Structural Verilog of ``c`` with a single scan chain."""
    module = module or f"{c.name}_scan"
    chain = chain or list(c.flops)
    if sorted(chain) != sorted(c.flops):
        raise ValueError("chain must contain every flop exactly once")
    v = _vname
    ports = ["clk", "scan_en", "scan_in"] + [v(i) for i in c.inputs] + [v(o) for o in c.outputs] + ["scan_out"]
    lines = [f"// Generated by memcore.atpg.scan.insert_scan from {c.name}.bench",
             f"// {len(chain)} scan flops, chain order: " + " -> ".join(chain),
             f"module {module} ({', '.join(ports)});",
             "  input clk, scan_en, scan_in;"]
    lines += [f"  input {v(i)};" for i in c.inputs]
    lines += [f"  output {v(o)};" for o in c.outputs]
    lines.append("  output scan_out;")
    nets = sorted(set(c.gates) - set(c.outputs) - set(c.inputs))
    lines += [f"  wire {v(n)};" for n in nets]
    for k, out in enumerate(c.order):
        g = c.gates[out]
        prim = {"BUF": "buf", "NOT": "not"}.get(g.type, g.type.lower())
        lines.append(f"  {prim} g{k} ({v(out)}, {', '.join(v(i) for i in g.ins)});")
    prev = "scan_in"
    for k, f in enumerate(chain):
        d = c.gates[f].ins[0]
        lines.append(f"  sdff sf{k} (.clk(clk), .d({v(d)}), .si({prev}), .se(scan_en), .q({v(f)}));")
        prev = v(f)
    lines.append(f"  assign scan_out = {prev};")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def export_patterns(c: Circuit, patterns: list[dict[str, int]], chain: list[str] | None = None) -> tuple[str, dict]:
    """Return (vector file text, layout) for the scan testbench.

    Each line: load[N] pi[P] po_expected[Q] capture_expected[N], all MSB =
    first field element, in chain order F0..F(N-1) for load/capture.
    """
    chain = chain or list(c.flops)
    fs = FaultSimulator(c)
    rows = []
    for pat in patterns:
        resp = fs.responses(pat)
        load = "".join(str(pat.get(f, 0)) for f in chain)
        pis = "".join(str(pat.get(i, 0)) for i in c.inputs)
        pos = "".join(str(resp[o]) for o in c.outputs)
        cap = "".join(str(resp[c.gates[f].ins[0]]) for f in chain)
        rows.append(load + pis + pos + cap)
    layout = {"n_flops": len(chain), "n_pi": len(c.inputs), "n_po": len(c.outputs),
              "width": 2 * len(chain) + len(c.inputs) + len(c.outputs), "n_patterns": len(rows)}
    return "\n".join(rows) + "\n", layout


def scan_testbench(c: Circuit, layout: dict, module: str | None = None, vec_file: str = "scan_vectors.mem") -> str:
    """Self-checking testbench applying the exported vectors through the chain."""
    module = module or f"{c.name}_scan"
    v = _vname
    n, p, q, w, npat = layout["n_flops"], layout["n_pi"], layout["n_po"], layout["width"], layout["n_patterns"]
    pi_assign = "\n".join(f"            {v(i)} = vec[{w - 1 - n - k}];" for k, i in enumerate(c.inputs))
    po_check = "\n".join(
        f"            if ({v(o)} !== vec[{w - 1 - n - p - k}]) begin po_err = po_err + 1; end"
        for k, o in enumerate(c.outputs))
    decl_pi = "\n".join(f"    reg {v(i)};" for i in c.inputs)
    decl_po = "\n".join(f"    wire {v(o)};" for o in c.outputs)
    conn = ", ".join([".clk(clk)", ".scan_en(scan_en)", ".scan_in(scan_in)", ".scan_out(scan_out)"]
                     + [f".{v(i)}({v(i)})" for i in c.inputs] + [f".{v(o)}({v(o)})" for o in c.outputs])
    return f"""// Generated scan-test testbench for {module}
`timescale 1ns/1ps
module tb_scan;
    reg clk = 0, scan_en = 0, scan_in = 0;
    wire scan_out;
{decl_pi}
{decl_po}
    reg [{w - 1}:0] vectors [0:{npat - 1}];
    reg [{w - 1}:0] vec;
    integer t, k, po_err, cap_err, chain_err;
    {module} dut ({conn});

`ifdef FAULT_NET
    initial force dut.`FAULT_NET = `FAULT_VAL;
`endif

    task pulse; begin #5 clk = 1; #5 clk = 0; end endtask

    initial begin
        $readmemb("{vec_file}", vectors);
        po_err = 0; cap_err = 0; chain_err = 0;
{chr(10).join(f"        {v(i)} = 0;" for i in c.inputs)}
        // chain integrity: shift an alternating 0011 pattern through
        scan_en = 1;
        for (k = 0; k < {n} + 8; k = k + 1) begin
            scan_in = (k / 2) % 2;
            if (k >= {n} && scan_out !== ((k - {n}) / 2) % 2) chain_err = chain_err + 1;
            pulse;
        end
        for (t = 0; t < {npat}; t = t + 1) begin
            vec = vectors[t];
            // load: shift F(N-1) first so that F0 receives the last bit
            scan_en = 1;
            for (k = {n} - 1; k >= 0; k = k - 1) begin
                scan_in = vec[{w - 1} - k];
                pulse;
            end
            // apply primary inputs and observe primary outputs
            scan_en = 0;
{pi_assign}
            #2;
{po_check}
            pulse;            // capture
            // unload: scan_out presents F(N-1) first
            scan_en = 1;
            for (k = {n} - 1; k >= 0; k = k - 1) begin
                #1;
                if (scan_out !== vec[{w - 1 - n - p - q} - k]) cap_err = cap_err + 1;
                pulse;
            end
        end
        $display("SCAN_RESULT patterns=%0d chain_err=%0d po_err=%0d capture_err=%0d", {npat}, chain_err, po_err, cap_err);
        $finish;
    end
endmodule
"""
